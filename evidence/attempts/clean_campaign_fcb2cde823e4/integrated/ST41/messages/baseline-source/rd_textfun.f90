  function cadjf(lres_, cin,isz)
    implicit none
    integer, intent(in) :: lres_
    character(len=lres_) :: cadjf
  !
    integer :: isz
    character(len=*) :: cin
  !
    character(len=1) :: blank
    parameter (blank = ' ')
    integer :: i, k, irs
  !
    intrinsic :: len, min
  !
  !     initialize return and reject empty/non-positive requests
    cadjf = blank
    if (len(cin) .gt. 0 .and. isz .gt. 0) then
  !       find the first non-blank character using input length as bound.
  !       This handles right-justified one-character flags such as
  !       '         D' without producing an invalid reversed substring.
      i = 1
      do while(i .le. len(cin))
        if (cin(i:i) .gt. blank) exit
        i = i+1
      end do
  !
      if (i .le. len(cin)) then
  !         copy no more than requested, available input, or return capaci
        k = len(cadjf)
        irs = min(isz,k,len(cin)-i+1)
        if (irs .gt. 0) cadjf(1:irs) = cin(i:i+irs-1)
      end if
    end if
  !
    return
  !
  end function cadjf

