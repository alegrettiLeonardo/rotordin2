    character(len=99) :: buf
    dimension buf(3)
    parameter(blank = ' ')
  !
    intrinsic :: len, min
  !
    do i = 1,3
      buf(i) = blank
    end do
    if (nemsg .gt. 0) then
      buf(1) = errmsgf(99, nemsg)
    end if
    i = len_trim(buf(1))
    if (i .gt. 0) then
      if (nwmsg .gt. 0) then
        buf(2) = warnmsgf(99, nwmsg)
        buf(3) = fmtmsgf(99, mname,buf(1),buf(2),usesep)
      else
        buf(3) = fmtmsgf(99, mname,buf(1),blank,usesep)
      end if
    end if
    i = len(femsgf)
    j = len(buf(3))
    k = min(i,j)
    femsgf = buf(3)(1:k)
  !
    return
  !
  end function femsgf

