  function famsgf(lres_, mname,nmsg,opttxt,usesep,ikd)
    implicit none
    integer, intent(in) :: lres_
    character(len=lres_) :: famsgf
  !
    character(len=*) :: mname, opttxt
    integer :: nmsg, usesep, ikd
  !
    integer :: i, j, k
    character(len=1) :: blank
    character(len=99) :: buf
    dimension buf(3)
    parameter(blank = ' ')
  !
    intrinsic :: len, len_trim, min
  !
    famsgf = blank
    do i = 1,3
      buf(i) = blank
    end do
    if (nmsg .gt. 0) then
  !       kind
      if (ikd .eq. 0) then
  !         0=error
        buf(1) = errmsgf(99, nmsg)
      else if (ikd .eq. 1) then
  !         1=warning
        buf(1) = warnmsgf(99, nmsg)
      else if (ikd .eq. 2) then
  !         2=help
        buf(1) = hlpmsgf(99, nmsg)
      else if (ikd .eq. 3) then
  !         3=matrix export
        buf(1) = mexmsgf(99, nmsg)
      end if
    end if
    i = len_trim(buf(1))
    if (i .gt. 0) then
      j = len_trim(opttxt)
      if (j .gt. 0) then
        buf(3) = fmtmsgf(99, mname,buf(1),opttxt,usesep)
      else
        buf(3) = fmtmsgf(99, mname,buf(1),blank,usesep)
      end if
    end if
    i = len(famsgf)
    j = len(buf(3))
    k = min(i,j)
    if (k .gt. 0) famsgf = buf(3)(1:k)
  !
    return
  !
  end function famsgf

  function femsgf(lres_, mname,nemsg,nwmsg,usesep)
    implicit none
    integer, intent(in) :: lres_
    character(len=lres_) :: femsgf
  !
    character(len=*) :: mname
    integer :: nemsg, nwmsg, usesep
  !
    integer :: i, j, k
