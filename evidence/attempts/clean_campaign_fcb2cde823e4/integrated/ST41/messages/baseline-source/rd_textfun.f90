  function xtime(lres_)
    use rd_kinds, only: lrk
    implicit none
    integer, intent(in) :: lres_
    character(len=lres_) :: xtime
  !
    integer :: lf
    character(len=1) :: blank
    character(len=3) :: cfm
    character(len=20) :: fmt, stime
    dimension cfm(2)
    parameter (blank = ' ',cfm = (/' (f','.2)'/))
    real(lrk) :: time
    real(lrk) :: values(2)
    data time/0/,values/2*0/
  !
  !     intrinsic functions
    intrinsic :: int, log10, min, len, len_trim

  !     intrinsic etime elapsed time
    call cpu_time(time)
  !     how much digits
    if (time .gt. 0) then
      lf = int(log10(time))+4
    else
      lf = 4
    end if
    if (lf .lt. 4) lf = 4
  !     time format string
    write(fmt,5) cfm(1),lf,cfm(2)
  !     buffer
    write(stime,fmt) time
  !     check size
    if (time .lt. 1) stime = blank//stime(1:)
  !     size of xtime
    lf = min(len(xtime),len_trim(stime))
    xtime = stime(1:lf)
  !
    return
  !
  5 format(a,i4,a)
  !
  end function xtime

