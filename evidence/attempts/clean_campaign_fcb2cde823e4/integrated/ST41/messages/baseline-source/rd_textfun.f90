  function msgf(lres_, imsg,ikd)
    use com_emsgs, only: emsg
    use com_hmsgs, only: hmsg
    use com_mmmsg, only: exmsg
    use com_pmsgs, only: pmsg
    use com_scmsg, only: lmc
    use com_tmsgs, only: tmsg
    use com_wmsgs, only: wmsg
    implicit none
    integer, intent(in) :: lres_
    character(len=lres_) :: msgf
  !
    integer :: imsg, ikd
  !
  !     matrix export error messages
    integer :: mxg0
    parameter (mxg0 = 15)
  !     error messages
    integer :: mxg1
    parameter (mxg1 = 35)
  !     warning messages
    integer :: mxg2
    parameter (mxg2 = 45)
  !     plot messages
    integer :: mxg3
    parameter (mxg3 = 70)
  !     help messages
    integer :: mxg4
    parameter (mxg4 = 30)
  !     output text messages
    integer :: mxg5
    parameter (mxg5 = 180)
  !     screen messages
    integer :: nsmsg
    parameter(nsmsg = 30)
  !
    integer :: i, j, k
    character(len=1) :: blank
    character(len=13) :: civ
    character(len=50) :: cms
    parameter (blank =' ',civ = 'invalid index')
  !
    intrinsic :: len, len_trim, min
  !
  !     init invalid
    msgf = blank
    cms = civ
    if (ikd .eq. 0) then
  !       matrix export error messages
      if (imsg .gt. 0 .and. imsg .le. mxg0) then
        cms = exmsg(imsg)
      end if
    else if (ikd .eq. 1) then
  !       error messages
      if (imsg .gt. 0 .and. imsg .le. mxg1) then
        cms = emsg(imsg)
      end if
    else if (ikd .eq. 2) then
  !       warning messages
      if (imsg .gt. 0 .and. imsg .le. mxg2) then
        cms = wmsg(imsg)
      end if
    else if (ikd .eq. 3) then
  !       plot messages
      if (imsg .gt. 0 .and. imsg .le. mxg3) then
        cms = pmsg(imsg)
      end if
    else if (ikd .eq. 4) then
  !       help messages
      if (imsg .gt. 0 .and. imsg .le. mxg4) then
        cms = hmsg(imsg)
      end if
    else if (ikd .eq. 5) then
  !       output text messages
      if (imsg .gt. 0 .and. imsg .le. mxg5) then
        cms = tmsg(imsg)
      end if
    else if (ikd .eq. 6) then
  !       screen messages
      if (imsg .gt. 0 .and. imsg .le. nsmsg) then
        cms = lmc(imsg)
      end if
    end if
  !     message size
    i = len_trim(cms)
  !     return size
    j = len(msgf)
  !     minimum
    k = min(i,j)
  !     return
    if (k .gt. 0) msgf = cms(1:k)
  !
    return
  !
  end function msgf

