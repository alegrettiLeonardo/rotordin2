  function fopmsf(lres_, mname,nemsg,pname,fname)
    implicit none
    integer, intent(in) :: lres_
    character(len=lres_) :: fopmsf
  !
    character(len=*) :: mname, pname, fname
    integer :: nemsg
  !
    integer :: i, j, k
    character(len=1) :: blank, ccm
    character(len=65) :: msg
    character(len=99) :: buf
    dimension ccm(2)
    parameter(blank = ' ',ccm = (/'(',')'/))
  !
    intrinsic :: len, len_trim, min
  !
    msg = blank
    buf = blank
    if (nemsg .gt. 0) then
      buf = errmsgf(99, nemsg)
    end if
  !     error message
    j = len_trim(buf)
  !     file name
    i = len_trim(fname)
  !     section name
    k = len_trim(pname)
  !     check message parts
    if (j .gt. 0 .and. k .gt. 0) then
  !       composed error message
      write(msg,5)buf(1:j),ccm(1),pname(1:k),ccm(2)
    else if (j .gt. 0) then
      write(msg,15)buf(1:j)
    end if
  !
    if (i .gt. 0) then
      fopmsf = fmtmsgf(99, mname,msg,fname(1:i),1)
    else
      fopmsf = fmtmsgf(99, mname,msg,blank,1)
    end if
  !
    return
  !
  5 format(4a)
  15 format(a)
  !
  end function fopmsf

