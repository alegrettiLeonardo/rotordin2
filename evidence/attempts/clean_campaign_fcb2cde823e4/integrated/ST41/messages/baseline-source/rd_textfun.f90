  function pgycscidf(lres_)
    use com_gycsedc, only: gycsedid, gycsedvl, ngycsed
    use rd_kinds, only: lrk
    implicit none
    integer, intent(in) :: lres_
    character(len=lres_) :: pgycscidf
  !
    integer :: mxgc
    parameter (mxgc = 5)
  !
    integer :: ii, jj, kk, ll
    character(len=1) :: bl, cm, cz, ds
    character(len=2) :: c2
    character(len=8) :: c8
    character(len=60) :: buf
  !
    parameter (bl = ' ',cm = ',',cz = '0',ds = '-')
    data buf/bl/
  !
    intrinsic :: len, len_trim, min
  !
    pgycscidf = bl
    do ii = 1,ngycsed
  !       id
      if (gycsedid(ii) .lt. 10) then
        write(c2,5) gycsedid(ii)
      else if (gycsedid(ii) .lt. 100) then
        write(c2,15) gycsedid(ii)
      else
  !         errror, not supposed to be

      end if
      jj = len_trim(c2)
  !       value
      write(c8,25) gycsedvl(ii)
  !       remove right zeros
      do ll = len(c8),1,-1
        if (c8(ll:ll) .ne. cz) exit
      end do
  !
      kk = len_trim(buf)
      if (ii .lt. ngycsed) then
        write(buf(kk+1:),35) c2(1:jj),ds,c8(1:ll),cm
      else
  !         last, no comma
        write(buf(kk+1:),45) c2(1:jj),ds,c8(1:ll)
      end if
  !
    end do
  !
    kk = len_trim(buf)
    ll = len(pgycscidf)
    jj = min(kk,ll)
    if (jj .gt. 0) pgycscidf = buf(1:jj)
  !
    return
  !
  5 format(i1)
  15 format(i2)
  25 format(f8.6)
  35 format(4a)
  45 format(3a)
  !
  end function pgycscidf

