  function sinfo(lres_, lgn,ifl)
    use com_inf, only: vrs, dta, rgh, sid
    use com_nmi, only: inm, sbv
    implicit none
    integer, intent(in) :: lres_
    character(len=lres_) :: sinfo
  !
    logical :: lgn
    integer :: ifl
  !
  !     internal name
  !
  !     system identification
  !
    integer :: i, j, iiff
    character(len=1) :: dl, blank
    character(len=3) :: vr, rv
    character(len=50) :: buf
    parameter (dl = '$',blank = ' ',vr = '-v:',rv = ' r:')
  !
    intrinsic :: len, len_trim, min
  !
    i = iiff(ifl .ne. 0,len_trim(sid),len_trim(inm))
  !     check for log info
    if (lgn) then
  !       log info -> dl
      if (ifl .ne. 0) then
  !         full application name, version, sub-version, revision
        write(buf,10) dl,sid(1:i),vr,vrs,sbv,rv,rvinfof(5, j)
      else
  !         short application name, version, sub-version, revision
        write(buf,10) dl,blank//inm(1:i),vr,vrs,sbv,rv,rvinfof(5, j)
      end if
    else
      if (ifl .ne. 0) then
  !         full application name, version, sub-version, revision
        write(buf,20) sid(1:i),vr,vrs,sbv,rv,rvinfof(5, j)
      else
  !         short application name, version, sub-version, revision
        write(buf,20) blank//inm(1:i),vr,vrs,sbv,rv,rvinfof(5, j)
      end if
    end if
  !     return size
    i = min(len(sinfo),len_trim(buf))
    sinfo = buf(1:i)
  !
    return
  !
  10 format(7a)
  20 format(6a)
  !
  end function sinfo

  function sjoinif(lres_, iin,sfm,nin,ndm)
    implicit none
    integer, intent(in) :: lres_
    character(len=lres_) :: sjoinif
  !
    integer :: iin, nin, ndm
    dimension iin(ndm)
    character(len=*) :: sfm
  !
    integer :: ii, io, jj, kk, ll, mm, nn
    character(len=1) :: c1
    character(len=7) :: nmm
    character(len=20) :: sdm
    dimension c1(2)
    parameter (c1 = (/' ',','/),nmm = 'sjoinif')
  !
    intrinsic :: len, len_trim
  !
    nn = 1
  !     buffer size
    mm = len(sdm)
  !     output size
    ll = len(sjoinif)
  !     init output with a blank
    sjoinif = c1(1)
  !     loop over input elements
    do ii = 1,nin
      kk = len_trim(sfm)
      if (kk .gt. 0) then
  !         write each element to a buffer using given format
        write(sdm,sfm(1:kk),err=10,iostat=io) iin(ii)
      else
        write(sdm,*,err=10,iostat=io) iin(ii)
      end if
  !       useful output buffer size
      jj = len_trim(sdm)
  !       search first non blank
      do kk = 1,jj
        nn = kk
        if (sdm(kk:kk) .gt. c1(1)) exit
      end do
  !       add comma if not last element and have size
      if (ii .lt. nin .and. jj .lt. mm) then
        sdm = sdm(nn:jj)//c1(2)
      else
        sdm = sdm(nn:jj)
      end if
      jj = len_trim(sdm)
  !       output size
      kk = len_trim(sjoinif)
      if (kk+jj .lt. ll) then
  !         have room to output
        sjoinif = sjoinif(1:kk)//sdm(1:jj+1)
      else
  !         no room left warning
        call elmsgw(0,2,nmm)
        exit
      end if
  !       write warning
  10  if (io .ne. 0) call elmsgw(0,32,nmm)
    end do
  !
    return
  !
  end function sjoinif

  function sjoinrf(lres_, rin,sfm,nin,ndm)
    use rd_kinds, only: lrk
    implicit none
    integer, intent(in) :: lres_
    character(len=lres_) :: sjoinrf
  !
    integer :: nin, ndm
    real(lrk) :: rin
    dimension rin(ndm)
    character(len=*) :: sfm
  !
    integer :: ii, io, jj, kk, ll, mm, nn, oo
    character(len=1) :: c1
    character(len=7) :: nmm
    character(len=20) :: sdm
    logical :: hcm
    dimension c1(4)
    parameter (c1 = (/' ',',','.','0'/),nmm = 'sjoinrf')
  !
    intrinsic :: index, len, len_trim
  !
  !     buffer size
    mm = len(sdm)
  !     output size
    ll = len(sjoinrf)
  !     init output with a blank
    sjoinrf = c1(1)
  !     loop over input elements
    do ii = 1,nin
      kk = len_trim(sfm)
  !       write each element to a buffer using given format
      if (kk .gt. 0) then
        write(sdm,sfm(1:kk),err=10,iostat=io) rin(ii)
      else
        write(sdm,*,err=10,iostat=io) rin(ii)
      end if
  !       useful output buffer size
      jj = len_trim(sdm)
  !       search first non blank
      do kk = 1,jj
        nn = kk
        if (sdm(kk:kk) .gt. c1(1)) exit
      end do
  !       add comma if not last element and have size
      if (ii .lt. nin .and. jj .lt. mm) then
        sdm = sdm(nn:jj)//c1(2)
      else
        sdm = sdm(nn:jj)
      end if
      jj = len_trim(sdm)
  !       has dot? check for at right zeros
      oo = index(sdm,c1(3))
      if (oo .gt. 0) then
  !         check for last comma
        hcm = sdm(jj:jj) .eq. c1(2)
  !         remove last comma from size
        if (hcm) jj = jj-1
  !         loop non significant zeros (at right)
        do kk = jj,oo+1,-1
          nn = kk
          if (sdm(kk:kk) .ne. c1(4)) exit
        end do
  !         remove non significant zeros (at right)
        sdm = sdm(1:nn)
  !         add coma again
        if (hcm) sdm = sdm(1:nn)//c1(2)
        jj = len_trim(sdm)
      end if
  !       output size
      kk = len_trim(sjoinrf)
      if (kk+jj .lt. ll) then
  !         have room to output
        sjoinrf = sjoinrf(1:kk)//sdm(1:jj+1)
      else
  !         no room left warning
        call elmsgw(0,2,nmm)
        exit
      end if
  !       write warning
  10  if (io .ne. 0) call elmsgw(0,32,nmm)
    end do
  !
    return
  !
  end function sjoinrf

  function tpeqstidf(lres_)
    use com_tstest, only: eqstid, ntest
    implicit none
    integer, intent(in) :: lres_
    character(len=lres_) :: tpeqstidf
  !
  !     equivalent stiffness for static
    integer :: mxtstf
    parameter (mxtstf = 5)
  !
    integer :: ii, jj, kk
    character(len=1) :: ccm
    character(len=5) :: bf1
    character(len=30) :: bf2
    dimension ccm(2)
    parameter (ccm = (/',','-'/))
  !
    intrinsic :: len, len_trim, min
  !
  !     output buffer
    bf2 = ' '
  !     loop on pairs
    do ii = 1,ntest
  !       check format for two indices
      if (eqstid(ii,1) .lt. 10 .and. eqstid(ii,2) .lt. 10) then
  !         both bellow 10
        write(bf1,5)eqstid(ii,1),ccm(2),eqstid(ii,2)
      else if (eqstid(ii,1) .lt. 10 .and. eqstid(ii,2) .gt. 9) then
  !         one bellow 10 other above 9
        write(bf1,15)eqstid(ii,1),ccm(2),eqstid(ii,2)
      else if (eqstid(ii,1) .gt. 9 .and. eqstid(ii,2) .lt. 10) then
  !         one bellow 10 other above 9
        write(bf1,25)eqstid(ii,1),ccm(2),eqstid(ii,2)
      else
  !         two above 9
        write(bf1,35)eqstid(ii,1),ccm(2),eqstid(ii,1)
      end if
  !       size of two intgers buffer
      kk = len_trim(bf1)
  !       size of output buffer
      jj = len_trim(bf2)
  !       coma just after first pair
      if(ii .eq. 1) then
        write(bf2(jj+1:),45)bf1(1:kk)
      else
        write(bf2(jj+1:),55)ccm(1),bf1(1:kk)
      end if
    end do
  !     function output size
    jj = len(tpeqstidf)
  !     output buffer size
    kk = len_trim(bf2)
  !     select minumum size
    ii = min(jj,kk)
  !     state output size
    tpeqstidf = bf2(1:ii)
  !
    return
  !
  5 format(i1,a,i1)
  15 format(i1,a,i2)
  25 format(i2,a,i1)
  35 format(i2,a,i2)
  45 format(a)
  55 format(2a)
  !
  end function tpeqstidf

