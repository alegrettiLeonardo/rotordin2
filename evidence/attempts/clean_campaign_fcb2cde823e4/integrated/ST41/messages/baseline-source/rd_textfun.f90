  function fmtmsgf(lres_, mname,msgtxt,opttxt,usesep)
    implicit none
    integer, intent(in) :: lres_
    character(len=lres_) :: fmtmsgf
  !
    integer :: usesep
    character(len=*) :: mname, msgtxt, opttxt
  !
    character(len=128) :: buf
    character(len=6) :: nomsg
    character(len=2) :: poi
    character(len=1) :: blank, sep
    dimension sep(2)
    parameter (poi = '->',blank = ' ',&
    &sep = (/'<','>'/),nomsg = 'no msg')
    integer :: ib, in, i1, ip, i2, i3, it
  !
    intrinsic :: len, len_trim, min
  !
    buf = blank
    fmtmsgf = blank
  !     lengths
  !     module name
    i1 = len_trim(mname)
  !     message text
    i2 = len_trim(msgtxt)
  !     optional text
    i3 = len_trim(opttxt)
  !     module name pointer length
    ip = len_trim(poi)
  !     no message length
    in = len_trim(nomsg)
  !     buffer length
    ib = len(buf)
  !
  !     has module name
    if (i1 .gt. 0) then
  !       message is not blank
      if (i2 .gt. 0) then
  !         total length
        it = min(i1+ip+i2+1,ib)
        write(buf(1:it),20) mname(1:i1),poi(1:ip),msgtxt(1:i2)
  !       message is blank
      else
        it = min(i1+ip+in+1,ib)
        write(buf(1:it),20) mname(1:i1),poi(1:ip),nomsg(1:in)
      end if
  !     module name is blank
    else
  !       message is not blank
      if (i2 .gt. 0) then
        it = i2
        write(buf(1:it),10) msgtxt(1:i2)
  !       message is blank
      else
        it = in
        write(buf(1:it),10) nomsg(1:it)
      end if
    end if
  !     optional text
    if (i3 .gt. 0) then
      it = it+1
  !       check for left space in buffer
      if (it .lt. ib) then
  !         optional text with separators
  !         may have truncation
        if (usesep .ne. 0) then
          i1 = min(ib-2,i3)
          write(buf(it:),20) sep(1),opttxt(1:i1),sep(2)
        else
          i1 = min(ib,i3)
          write(buf(it:),10) opttxt(1:i1)
        end if
      end if
    end if
  !     total buffer length
    it = len_trim(buf)
  !     function return defined length
    in = len(fmtmsgf)
  !     check max return length
    i1 = min(in,it)
    if (i1 .gt. 0) fmtmsgf = buf(1:i1)
  !
    return
  !
  10 format(a)
  20 format(3a)
  !
  end function fmtmsgf

